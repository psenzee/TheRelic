static int GetCount(const char **list)
{
    const char **p = list;
    int i = 0;
    for (; *p; i++) p++;
    return i;
}

PlaceNameGenerator::PlaceNameGenerator() : mAdjectivesCount(0), mPlaceNamesCount(0), mNamesCount(0)
{
    mAdjectivesCount = GetCount(adjectives);
    mPlaceNamesCount = GetCount(placeNames);
    mNamesCount      = GetCount(names);
}

static const char *copy_with_the(const char *phrase, bool the, bool capital, char *into, size_t size)
{
    if (phrase[0] == '.') {
        snprintf(into, size, "%s", phrase + 1);
    } else {
        snprintf(into, size, "%s%s", the ? (capital ? "The " : "the ") : "", phrase);
    }
    return into;
}

const char *PlaceNameGenerator::FormatName(const char *adjective, const char *place, const char *name, bool possessive) const
{
    static char buffer[1024] = { 0 }, pn[1024] = { 0 }, n[1024] = { 0 };
    size_t sz = sizeof(buffer) - 1;
    const char *adj = adjective ? adjective : "";
    snprintf(buffer, sz, "%s%s%s", adj, adjective ? " " : "", place);
    copy_with_the(buffer, !possessive, true,  pn, sz);
    copy_with_the(name,   true,        false, n,  sz);
    if (possessive) {
        const char *aposs = (name[strlen(name) - 1] == 's') ? "'" : "'s";
        snprintf(buffer, sz, "%s%s %s", n, aposs, pn);
    } else {
        snprintf(buffer, sz, "%s of %s", pn, n);
    }
    return buffer;
}

const char *PlaceNameGenerator::GetPlaceName(core::Random &random) const
{
    int number0 = random.integer(),
        number1 = random.integer(),
        number2 = random.integer();

    const char *adjective = adjectives[number0 % mAdjectivesCount];
    const char *placeName = placeNames[number1 % mPlaceNamesCount];
    const char *name      = names     [number2 % mNamesCount];

    if (random.realf() < 0.5f) adjective = 0;

    snprintf(mName, MAX_PLACENAME_SIZE - 1, "%s", FormatName(adjective, placeName, name, random.realf() < 0.5f));
    return mName;
}
